/**
 * One-command Firebase setup (after `npx firebase-tools login`).
 * Creates project, Firestore, web app, .env, and deploys security rules.
 */
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const firebase = 'npx firebase-tools';
const FIREBASE_CLIENT_ID =
  '563584335869-fgrhgmd47bqnekij2ip96l1clg8acf06.apps.googleusercontent.com';

function run(cmd, options = {}) {
  return execSync(cmd, {
    encoding: 'utf8',
    cwd: root,
    stdio: options.silent ? 'pipe' : 'inherit',
    ...options,
  });
}

function runSilent(cmd) {
  return run(cmd, { silent: true });
}

function checkAuth() {
  try {
    runSilent(`${firebase} projects:list`);
    return true;
  } catch {
    return false;
  }
}

function getFirebaseConfigPath() {
  const appData = process.env.APPDATA ?? resolve(homedir(), '.config');
  return resolve(appData, 'configstore', 'firebase-tools.json');
}

async function getAccessToken() {
  const path = getFirebaseConfigPath();
  if (!existsSync(path)) {
    throw new Error('Firebase credentials not found. Run: npx firebase-tools login');
  }

  const data = JSON.parse(readFileSync(path, 'utf8'));
  const refreshToken =
    data.tokens?.refresh_token ??
    data.tokens?.default?.refresh_token ??
    data.users?.default?.tokens?.refresh_token;

  if (!refreshToken) {
    throw new Error('No refresh token in firebase-tools config. Run: npx firebase-tools login');
  }

  const body = new URLSearchParams({
    client_id: FIREBASE_CLIENT_ID,
    refresh_token: refreshToken,
    grant_type: 'refresh_token',
  });

  const res = await fetch('https://oauth2.googleapis.com/token', {
    method: 'POST',
    headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
    body,
  });

  if (!res.ok) {
    throw new Error(`Token refresh failed (${res.status}). Run: npx firebase-tools login`);
  }

  const json = await res.json();
  return json.access_token;
}

async function enableEmailPasswordAuth(projectId, accessToken) {
  const url = `https://identitytoolkit.googleapis.com/v2/projects/${projectId}/config?updateMask=signIn.email.enabled,signIn.email.passwordRequired`;
  const res = await fetch(url, {
    method: 'PATCH',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json',
      'X-Goog-User-Project': projectId,
    },
    body: JSON.stringify({
      signIn: {
        email: {
          enabled: true,
          passwordRequired: true,
        },
      },
    }),
  });

  if (!res.ok) {
    const text = await res.text();
    console.warn('⚠️  Could not auto-enable Email/Password auth via API.');
    console.warn(`   Open: https://console.firebase.google.com/project/${projectId}/authentication/providers`);
    console.warn(`   Enable Email/Password manually. (${res.status}: ${text.slice(0, 120)})`);
    return false;
  }

  console.log('✅ Email/Password authentication enabled.');
  return true;
}

function parseAppsList(jsonText) {
  const data = JSON.parse(jsonText);
  const apps = data.results ?? data.result ?? [];
  return apps;
}

function writeEnvFromSdk(projectId, sdkConfig) {
  const env = `# Firebase — auto-generated by scripts/setup-firebase.mjs
VITE_DATA_SOURCE=firebase
VITE_APP_ENV=development

VITE_FIREBASE_API_KEY=${sdkConfig.apiKey}
VITE_FIREBASE_AUTH_DOMAIN=${sdkConfig.authDomain ?? `${projectId}.firebaseapp.com`}
VITE_FIREBASE_PROJECT_ID=${sdkConfig.projectId ?? projectId}
VITE_FIREBASE_STORAGE_BUCKET=${sdkConfig.storageBucket ?? `${projectId}.appspot.com`}
VITE_FIREBASE_MESSAGING_SENDER_ID=${sdkConfig.messagingSenderId}
VITE_FIREBASE_APP_ID=${sdkConfig.appId}
`;

  writeFileSync(resolve(root, '.env'), env);
  console.log('✅ Wrote .env with Firebase config.');
}

function writeFirebaserc(projectId) {
  writeFileSync(
    resolve(root, '.firebaserc'),
    JSON.stringify({ projects: { default: projectId } }, null, 2) + '\n',
  );
}

async function main() {
  console.log('🔥 Nugawela Firebase setup\n');

  if (!checkAuth()) {
    console.error('❌ Not logged in to Firebase.');
    console.error('   Run:  npx firebase-tools login');
    console.error('   Then: npm run firebase:setup');
    process.exit(1);
  }

  const suffix = Date.now().toString().slice(-6);
  const projectId = `nugawela-resort-${suffix}`;

  console.log(`Creating Firebase project: ${projectId} …`);
  try {
    run(`${firebase} projects:create ${projectId} --display-name "Nugawela Escape Resort"`);
  } catch (error) {
    console.error('Failed to create project. Try a different project ID or use an existing project.');
    throw error;
  }

  writeFirebaserc(projectId);
  run(`${firebase} use ${projectId}`);

  console.log('Creating Firestore database (asia-south1) …');
  try {
    run(`${firebase} firestore:databases:create "(default)" --location asia-south1`);
  } catch {
    console.warn('⚠️  Firestore may already exist — continuing.');
  }

  console.log('Creating web app …');
  run(`${firebase} apps:create WEB "Nugawela Web" --project ${projectId}`);

  const appsJson = runSilent(`${firebase} apps:list WEB --project ${projectId} --json`);
  const apps = parseAppsList(appsJson);
  const webApp = apps.find((a) => a.platform === 'WEB') ?? apps[0];

  if (!webApp?.appId) {
    throw new Error('Could not find web app ID after creation.');
  }

  const sdkJson = runSilent(
    `${firebase} apps:sdkconfig WEB ${webApp.appId} --project ${projectId} --json`,
  );
  const sdkPayload = JSON.parse(sdkJson);
  const sdkConfig = sdkPayload.result?.sdkConfig ?? sdkPayload.sdkConfig ?? sdkPayload;

  writeEnvFromSdk(projectId, sdkConfig);

  console.log('Enabling Email/Password sign-in …');
  const token = await getAccessToken();
  await enableEmailPasswordAuth(projectId, token);

  console.log('Deploying Firestore security rules …');
  run(`${firebase} deploy --only firestore:rules --project ${projectId}`);

  console.log('\n🎉 Firebase setup complete!\n');
  console.log(`   Project:  ${projectId}`);
  console.log(`   Console:  https://console.firebase.google.com/project/${projectId}`);
  console.log('\nNext: npm run dev');
  console.log('Demo logins (auto-seeded on first load):');
  console.log('   guest@nugawela.com / guest123');
  console.log('   admin@nugawela.com / admin123');
}

main().catch((error) => {
  console.error('\n❌ Setup failed:', error.message ?? error);
  process.exit(1);
});
